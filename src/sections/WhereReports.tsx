import { useState } from 'react'

import Reveal from '../components/Reveal'
import { ArrowRight, Check } from '../components/icons'
import { ACCOUNTS, SOURCES, accountsCsv } from '../components/where-data'

/* ---------------------------------------------------------------------------
   Where it goes, section 6 of 8: what we file, and where to read it.

   THE MENU LINKS TO "ANNUAL REPORTS & FINANCIALS" AND THERE ARE NONE
   A small charity is not required to lodge a financial report and Al-Anwaar
   has not lodged one. The obvious build — a shelf of report covers with
   download arrows — would be advertising documents that do not exist, on the
   one page that cannot afford it. What the charity does lodge is an Annual
   Information Statement every year, and the ACNC republishes all of them as
   open data, so this section hands over the sources themselves and lets anyone
   rebuild the table in section 2 from scratch.

   THE CSV IS THE POINT OF THE SECTION
   Every accountability page says "you can check this". This one hands over the
   file. It is written from ACCOUNTS — the same array the table renders from —
   so a downloaded copy can never disagree with the printed one, and the column
   headings are the AIS field names rather than the table's shortened ones, so
   a reader comparing it against the open data is comparing like with like.

   It is built in the browser with a Blob rather than served as a static file,
   for the same reason: a file in public/ is a second copy of the figures that
   would have to be regenerated by hand every time a year is added, and one day
   would not be. Nothing is uploaded and nothing is fetched.

   The tick after a download is the contact form's rule — never show a
   confirmation for something that did not happen — running the easy way for
   once, because here it always does.
--------------------------------------------------------------------------- */

export default function WhereReports() {
  const [saved, setSaved] = useState(false)

  const download = () => {
    const blob = new Blob([accountsCsv()], { type: 'text/csv;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'al-anwaar-annual-information-statements.csv'
    a.click()
    /* Revoked on the next tick rather than immediately — Safari has not always
       finished with the URL by the time click() returns. */
    setTimeout(() => URL.revokeObjectURL(url), 1000)

    setSaved(true)
    setTimeout(() => setSaved(false), 2600)
  }

  return (
    <section
      id="reports"
      aria-labelledby="reports-head"
      className="scroll-mt-[calc(var(--header-h)+24px)] bg-paper py-s5 lg:py-s6"
    >
      <div className="gutter mx-auto max-w-page">
        <div className="grid gap-s4 lg:grid-cols-[minmax(0,4fr)_minmax(0,8fr)] lg:gap-s5">
          <div>
            <p className="flex items-center gap-3 text-[11px] font-semibold tracking-[0.16em] text-green uppercase">
              <span aria-hidden="true" className="h-px w-6 bg-green/40" />
              Reports &amp; financials
            </p>
            <h2
              id="reports-head"
              className="mt-s1 max-w-[16ch] font-display text-[clamp(26px,3vw,38px)] leading-snug"
            >
              What we file, and where to read it
            </h2>
            <p className="mt-s2 max-w-measure text-[15.5px] leading-relaxed text-text-2">
              We publish no annual report, because we lodge none. Under the ACNC&rsquo;s
              thresholds a small charity files an Annual Information Statement each year and is
              not required to lodge audited financial statements, so rather than write our
              own summary of ourselves, here is every source the figures on this page come from.
            </p>
          </div>

          <div>
            <ul>
              {SOURCES.map((source, i) => (
                <Reveal key={source.href} delay={i * 60}>
                  <li className="border-t border-line">
                    <a
                      href={source.href}
                      target="_blank"
                      rel="noreferrer"
                      className="group flex items-start justify-between gap-s3 py-s3 transition-colors duration-200 ease-brand hover:text-green"
                    >
                      <span className="max-w-measure">
                        <span className="block font-display text-[clamp(18px,1.6vw,21px)] leading-snug tracking-[-0.012em]">
                          {source.label}
                        </span>
                        <span className="mt-1.5 block text-[14px] leading-relaxed text-text-2">
                          {source.note}
                        </span>
                      </span>
                      <ArrowRight
                        className="mt-1.5 h-4 w-4 shrink-0 -rotate-45 text-text-3 transition-all duration-200 ease-brand group-hover:translate-x-1 group-hover:text-green"
                      />
                    </a>
                  </li>
                </Reveal>
              ))}
            </ul>

            {/* The figures themselves, as a file. */}
            <div className="mt-s3 flex flex-wrap items-center gap-s2 border-t border-line pt-s3">
              <button
                type="button"
                onClick={download}
                className="inline-flex items-center gap-2 rounded-[3px] border border-text px-s2 py-2.5 text-[14px] font-semibold transition-colors duration-200 ease-brand hover:bg-text hover:text-paper"
              >
                {saved ? <Check className="h-4 w-4" /> : null}
                {saved ? 'Saved' : 'Download the figures as a CSV'}
              </button>
              <p className="max-w-measure text-[13px] leading-relaxed text-text-3">
                All <span className="nums">{ACCOUNTS.length}</span> years, with the ACNC&rsquo;s
                own field names as the column headings, so you can check our arithmetic against
                the register line for line.
              </p>
            </div>
          </div>
        </div>
      </div>
    </section>
  )
}
